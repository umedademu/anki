const hanPattern = /[\p{Script=Han}々ヶ]/u;

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function addRequiredReadings(text) {
  const source = String(text ?? "");
  const protectedValues = [];
  const entries = Object.entries(requiredHistoryReadings).sort(
    ([left], [right]) => right.length - left.length,
  );
  let result = source;
  for (const [term, reading] of entries) {
    const annotated = `${term}(${reading})`;
    result = result.replaceAll(annotated, () => {
      const key = `\uE000${protectedValues.length}\uE001`;
      protectedValues.push(annotated);
      return key;
    });
  }

  for (const [term, reading] of entries) {
    if (source.includes(`${term}(${reading})`)) {
      continue;
    }
    const escaped = escapeRegExp(term);
    const pattern =
      [...term].length === 1 && hanPattern.test(term)
        ? new RegExp(`(?<![\\p{Script=Han}々ヶ])${escaped}(?![\\p{Script=Han}々ヶ])`, "u")
        : new RegExp(escaped, "u");
    result = result.replace(pattern, () => {
      const annotated = `${term}(${reading})`;
      const key = `\uE000${protectedValues.length}\uE001`;
      protectedValues.push(annotated);
      return key;
    });
  }

  return result.replace(/\uE000(\d+)\uE001/g, (_, index) => protectedValues[Number(index)]);
}

export function hasMissingRequiredReadings(text) {
  const source = String(text ?? "");
  return addRequiredReadings(source) !== source;
}
